def generate_sample_articles():
    """快速生成示例文章"""
    print("🚀 快速初始化文章库")
    print("="*50)
    
    lib = ArticleLibrary()
    
    # 扩展模板到20篇（通过变体）
    angles = ["实战派", "深度派", "故事派", "数据派", "趋势派"]
    
    count = 0
    for template in ARTICLE_TEMPLATES:
        base_topic = template["topic"]
        base_title = template["title"]
        base_content = template["content"]
        
        # 每篇模板生成5个变体（不同角度）
        for i, angle in enumerate(angles):
            title = base_title.replace("底层逻辑", f"{angle}视角").replace("实战", f"{angle}方法论").replace("冷启动", f"{angle}策略")[:50]
            
            aid = lib.save_candidate(
                title=title,
                topic=base_topic,
                content=base_content,
                candidate_num=i+1,
                angle=angle,
                quality_score=8.0 + (i * 0.1)
            )
            count += 1
            print(f"✓ {aid} - {title[:35]}...")
    
    print("="*50)
    print(f"🎉 已生成 {count} 篇文章")
    
    # 显示统计
    stats = lib.get_library_stats()
    print(f"📊 文章库: {stats['total']}篇")
    print(f"📚 访问: http://154.9.252.35:8080/library")

if __name__ == '__main__':
    generate_sample_articles()
